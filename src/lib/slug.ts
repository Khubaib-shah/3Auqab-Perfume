/**
 * Utility to convert arbitrary text (product names, blog titles, category names)
 * into clean, URL-safe SEO slugs.
 */
export function generateSlug(text: string): string {
  return text
    .toLowerCase()
    .trim()
    .replace(/[^\w\s-]/g, "")
    .replace(/[\s_-]+/g, "-")
    .replace(/^-+|-+$/g, "");
}
